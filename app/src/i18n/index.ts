/**
 * 表示文言。
 *
 * ⚠ **翻訳ではなく書き直しであること。**「喝」は禅で眠っている者を叩き起こす一喝で、
 *   罰でも罵倒でもない(spec §1 語義の定義)。直訳すると日本語では力が抜けるか、
 *   逆に人格否定に寄る。**同じ強さを持つ日本語**を書くこと。
 *
 * ⚠ **ユーザーが書いた言葉は絶対にここに入らない。**ここにあるのはアプリの地の文だけ。
 *   通知の本文はユーザーの文言そのものなので、この仕組みを一切通さない。
 *
 * ⚠ ライブラリを足さない。文言は80個程度で、辞書を1つ引くだけで足りる。
 *   依存を増やすほどの問題ではない。
 *
 * 端末の言語が日本語なら日本語、それ以外は英語。
 * 言語の切り替え画面は**作らない** ── 1.0 の画面は3つだけ(CLAUDE.md スコープ)。
 */

import { getLocales } from 'expo-localization';

import { en, type Copy } from '@/i18n/en';
import { ja } from '@/i18n/ja';

export type { Copy };

/**
 * 端末の言語を1回だけ読む。
 *
 * ⚠ 起動中に言語を切り替える人はいないので、毎回読み直さない。
 *   iOS は言語変更でアプリを再起動するため、これで取りこぼさない。
 */
function resolve(): Copy {
  try {
    const code = getLocales()[0]?.languageCode;
    return code === 'ja' ? ja : en;
  } catch {
    // 取れなくてもアプリを止めない。英語で通す
    return en;
  }
}

export const t: Copy = resolve();
