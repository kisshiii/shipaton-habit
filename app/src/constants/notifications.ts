/**
 * ローカル通知の制限。
 *
 * ⚠ iOS が保持できる予約通知は**アプリ全体で64件**まで。溢れた分は黙って捨てられる。
 *   `MAX_ROUTINES(8) × SCHEDULE_DAYS_AHEAD(7) = 56` で収まる計算にしてある。
 *   どちらかを増やすときは必ず掛け算を確認すること(spec §4 通知実装の制約-2)。
 */

export const IOS_SCHEDULED_LIMIT = 64;

/**
 * 何日先まで予約しておくか。
 *
 * 「未完了なら通知」は事前予約では表現できないため、**先に予約して完了時に消す**
 * 逆向きの実装になる(spec §4-3)。毎日繰り返しトリガーだと今日の分だけを
 * 取り消せないので、1日1件の単発通知を並べる形にしている。
 * アプリを開くたびに引き直すので、7日開かなくても通知が尽きない。
 */
export const SCHEDULE_DAYS_AHEAD = 7;
